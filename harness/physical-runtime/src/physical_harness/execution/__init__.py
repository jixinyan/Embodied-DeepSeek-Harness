"""Worker port; standalone action admission lives in action_gate and policy_rollout."""
from typing import Protocol
from physical_harness.wire import WireObject


class ExecutionWorker(Protocol):
    """Provider boundary; invocation requires a future concrete adapter."""
    async def submit(self, request: WireObject, idempotency_key: str) -> str: ...
    async def query(self, execution_id: str) -> WireObject: ...
    async def pause(self, execution_id: str) -> None: ...
    async def stop(self, execution_id: str) -> None: ...
